// ========================================
// LOAD PRODUCTS SAVED IN BROWSER
// ========================================

let active = 'All';
let visible = 8;

const extra = JSON.parse(
    localStorage.getItem('bakery-products') || '[]'
);

catalog.push(...extra);


// ========================================
// ELEMENTS
// ========================================

const products = document.querySelector('#products');

const count = document.querySelector('#result-count');

const load = document.querySelector('#load-more');


// ========================================
// RENDER PRODUCTS
// ========================================

function render() {

    const searchInput = document.querySelector('#search');

    const q = searchInput
        ? searchInput.value.toLowerCase().trim()
        : '';


    const list = catalog.filter(p => {

        const categoryMatch =
            active === 'All' || p[1] === active;

        const searchMatch =
            `${p[0]} ${p[1]} ${p[3]}`
                .toLowerCase()
                .includes(q);

        return categoryMatch && searchMatch;

    });


    const visibleProducts =
        list.slice(0, visible);


    products.innerHTML =
        visibleProducts.map((p, i) => {

            return `

            <article class="product">

                <div
                    class="product-image"
                    style="background-image:url('${p[4]}')">

                    ${i < 4
                        ? '<span class="tag">Fresh</span>'
                        : ''
                    }

                    <button
                        class="enquire"
                        data-name="${p[0]}">

                        Enquire on WhatsApp

                    </button>

                </div>


                <div class="product-info">

                    <div>

                        <h3>
                            ${p[0]}
                        </h3>

                        <p>
                            ${p[3]}
                        </p>

                    </div>


                    <span class="price">

                        ₹${p[2].toLocaleString('en-IN')}

                    </span>

                </div>

            </article>

            `;

        }).join('');


    // Result count

    count.textContent =
        `Showing ${Math.min(visible, list.length)} of ${list.length} treats`;


    // Show more button

    load.style.display =
        list.length > visible
            ? 'block'
            : 'none';


    // WhatsApp buttons

    document.querySelectorAll('.enquire')
        .forEach(button => {

            button.onclick = () => {

                const productName =
                    button.dataset.name;


                const message =
                    `Hi Hearth & Crumb, I would like to enquire about ${productName}.`;


                const whatsappURL =
                    `https://wa.me/918709675567?text=${encodeURIComponent(message)}`;


                window.open(
                    whatsappURL,
                    '_blank'
                );

            };

        });

}


// Initial render

render();


// ========================================
// CATEGORY FILTER
// ========================================

document.querySelectorAll('.filter')
    .forEach(button => {

        button.onclick = () => {

            const currentActive =
                document.querySelector('.filter.active');


            if (currentActive) {
                currentActive.classList.remove('active');
            }


            button.classList.add('active');


            active =
                button.dataset.category;


            visible = 8;


            render();

        };

    });


// ========================================
// SEARCH
// ========================================

const search =
    document.querySelector('#search');


if (search) {

    search.oninput = () => {

        visible = 8;

        render();

    };

}


// ========================================
// SHOW MORE
// ========================================

load.onclick = () => {

    visible += 8;

    render();

};


// ========================================
// MOBILE MENU
// ========================================

const menu =
    document.querySelector('.menu');


const mobile =
    document.querySelector('.mobile-menu');


if (menu && mobile) {

    menu.onclick = () => {

        const open =
            menu.classList.toggle('open');


        mobile.classList.toggle(
            'open',
            open
        );


        menu.setAttribute(
            'aria-expanded',
            open
        );

    };


    mobile
        .querySelectorAll('a')
        .forEach(link => {

            link.onclick = () => {

                menu.click();

            };

        });

}


// ========================================
// ADD PRODUCT MODAL
// ========================================

const modal =
    document.querySelector('#modal');


const adminButton =
    document.querySelector('.admin-open');


const closeButton =
    document.querySelector('.modal-close');


if (adminButton) {

    adminButton.onclick = () => {

        modal.classList.add('show');

    };

}


if (closeButton) {

    closeButton.onclick = () => {

        modal.classList.remove('show');

    };

}


if (modal) {

    modal.onclick = event => {

        if (event.target === modal) {

            modal.classList.remove('show');

        }

    };

}


// ========================================
// ADD NEW BAKERY PRODUCT
// ========================================

const productForm =
    document.querySelector('#product-form');


if (productForm) {

    productForm.onsubmit = event => {

        event.preventDefault();


        const formData =
            new FormData(productForm);


        const name =
            formData.get('name');


        const item = [

            name,

            formData.get('category'),

            Number(
                formData.get('price')
            ),

            formData.get('description') ||
            'Freshly baked · Made today',

            formData.get('image') ||
            'images/bakery-hero.png'

        ];


        // Save in browser

        extra.push(item);


        localStorage.setItem(
            'bakery-products',
            JSON.stringify(extra)
        );


        // Add immediately

        catalog.push(item);


        // Close modal

        modal.classList.remove('show');


        // Show more products

        visible = 40;


        render();


        productForm.reset();

    };

}


// ========================================
// CONTACT FORM
// ========================================

const contactForm =
    document.querySelector('#contact-form');


if (contactForm) {

    contactForm.onsubmit = event => {

        event.preventDefault();


        const formData =
            new FormData(contactForm);


        const name =
            formData.get('name');


        const phone =
            formData.get('phone');


        const message =
            formData.get('message');


        const whatsappMessage =
            `Hi Hearth & Crumb,

My name is ${name}.

Phone: ${phone}

I would like to order:
${message}`;


        const whatsappURL =
            `https://wa.me/918709675567?text=${encodeURIComponent(whatsappMessage)}`;


        window.open(
            whatsappURL,
            '_blank'
        );


        const status =
            contactForm.querySelector(
                '.form-message'
            );


        if (status) {

            status.textContent =
                'Opening WhatsApp...';

        };


        contactForm.reset();

    };

}
